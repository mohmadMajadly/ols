"""تطبيع النص العربي للمقارنة الصوتية (كتبه المدير — قلب دقة التتبع).

الهدف: تحويل كلمة من النص العثماني (بكامل ضبطه وعلاماته) وكلمة من مخرجات
Whisper (إملاء قياسي) إلى صورة موحدة تصلح للمقارنة الضبابية. التطبيع
متعمد الخشونة: نتسامح في الفروق الإملائية (همزات، ألف مقصورة، تاء مربوطة)
لأن الحكم النهائي بالمشابهة الحرفية بعد التطبيع، لا بالتطابق الصارم.
"""

import re
import unicodedata

# علامات الضبط والوقف والرموز القرآنية الصغيرة — كلها من فئات Unicode Mn/Me/Cf
# لكن نحصرها نطاقاً حتى لا نعتمد على تصنيف مكتبة قد يتغير.
_MARKS = re.compile(
    "["
    "ً-ٟ"  # التنوين والحركات والسكون والشدة...
    "ؐ-ؚ"  # علامات قرآنية (صلى الله عليه وسلم المصغرة ونحوها)
    "ۖ-ۭ"  # علامات الوقف الصغيرة ورموز السجدة والحزب
    "ـ"         # التطويل
    "࣓-ࣿ"  # امتدادات علامات قرآنية
    "]"
)

# حروف تُوحَّد إلى صورة واحدة
_CHAR_MAP = str.maketrans(
    {
        "أ": "ا",
        "إ": "ا",
        "آ": "ا",
        "ٱ": "ا",  # ألف الوصل العثمانية
        # الألف الخنجرية → ألف كاملة: الإملاء القياسي (مخرجات Whisper) يكتبها
        # ألفاً في الغالب (صرٰط→صراط، عٰلمين→عالمين، مٰلك→مالك)؛ والاستثناءات
        # (كالرحمٰن→الرحمن) يلتقطها التشابه الضبابي بفارق حرف واحد.
        "ٰ": "ا",
        "ى": "ي",
        "ئ": "ي",
        "ؤ": "و",
        "ة": "ه",
        "ء": "",
    }
)

_NON_ARABIC = re.compile(r"[^ء-ي]")


def normalize_word(word: str) -> str:
    """يعيد الصورة الموحدة للكلمة؛ سلسلة فارغة إن لم يبق منها حروف عربية."""
    w = unicodedata.normalize("NFC", word)
    w = _MARKS.sub("", w)
    w = w.translate(_CHAR_MAP)
    w = _NON_ARABIC.sub("", w)
    return w


def normalize_text(text: str) -> list[str]:
    """يقسّم نصاً حراً (مخرجات Whisper) إلى كلمات مطبَّعة، مسقطاً الفارغ."""
    out = []
    for token in text.split():
        n = normalize_word(token)
        if n:
            out.append(n)
    return out
